// `npm run dev:env`: writes apps/<app>/.env.local with local development values (git-ignored), mirroring the
// backend's `npm run dev:env`. Each app gets its own random session key. Existing files are kept unless
// `npm run dev:env -- --force` is used. Values match CLAUDE.md §2 ports and design 01 §9.
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const APPS = { storefront: 4100, seller: 4101, admin: 4102, agent: 4103 };
const BACKEND_ORIGIN = 'http://localhost:3100'; // backend api on host port 3100 (CLAUDE.md §13)
const REALTIME_ORIGIN = 'http://localhost:3001'; // backend realtime service (design 01 §15.8)
const MEDIA_ORIGIN = 'http://localhost:9100'; // MinIO: public images, presigned images and uploads (design 01 §15.8)
const UPLOADING_APPS = new Set(['storefront', 'seller', 'admin']); // the agent app uploads nothing
const force = process.argv.includes('--force');
const root = resolve(import.meta.dirname, '..');

const url = (port) => `http://localhost:${port}`;

for (const [app, port] of Object.entries(APPS)) {
  const file = resolve(root, 'apps', app, '.env.local');
  if (existsSync(file) && !force) {
    console.log(`kept    apps/${app}/.env.local (use -- --force to overwrite)`);
    continue;
  }
  const keyRing = JSON.stringify({ dev1: randomBytes(32).toString('base64') });
  const lines = [
    '# Local development only. Generated by `npm run dev:env`; never commit.',
    `APP_ORIGIN=${url(port)}`,
    `NILE_API_BASE_URL=${BACKEND_ORIGIN}`,
    // Single quotes keep the JSON literal for the env-file parser.
    `SESSION_ENCRYPTION_KEYS='${keyRing}'`,
    'SESSION_ACTIVE_KEY_ID=dev1',
    'SESSION_COOKIE_SECURE=false',
    'REFRESH_SKEW_SECONDS=60',
    'BFF_UPSTREAM_TIMEOUT_MS=15000',
    'BFF_MAX_BODY_KB=64',
    'LOG_LEVEL=debug',
    `NEXT_PUBLIC_APP_NAME=${app}`,
    `NEXT_PUBLIC_STOREFRONT_URL=${url(APPS.storefront)}`,
    `NEXT_PUBLIC_SELLER_URL=${url(APPS.seller)}`,
    `NEXT_PUBLIC_ADMIN_URL=${url(APPS.admin)}`,
    `NEXT_PUBLIC_AGENT_URL=${url(APPS.agent)}`,
    'NEXT_PUBLIC_REFRESH_SKEW_SECONDS=60',
    `NEXT_PUBLIC_REALTIME_URL=${REALTIME_ORIGIN}`,
    `NEXT_PUBLIC_MEDIA_PUBLIC_ORIGIN=${MEDIA_ORIGIN}`,
    ...(UPLOADING_APPS.has(app)
      ? [
          `NEXT_PUBLIC_MEDIA_PRIVATE_ORIGIN=${MEDIA_ORIGIN}`,
          `NEXT_PUBLIC_MEDIA_UPLOAD_ORIGIN=${MEDIA_ORIGIN}`,
        ]
      : []),
    ...(app === 'storefront' ? ['NEXT_PUBLIC_KASHIER_PAYMENT_WINDOW_MINUTES=15'] : []),
  ];
  writeFileSync(file, `${lines.join('\n')}\n`, { encoding: 'utf8', mode: 0o600 });
  console.log(`wrote   apps/${app}/.env.local`);
}
