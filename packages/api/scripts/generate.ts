// `npm run api:gen -w @nile/api`: snapshot → corrections (openapi-fix.ts) → openapi-typescript → schema.d.ts.
// `npm run api:check -w @nile/api` (CI drift check): same pipeline without writing; fails when the committed
// file differs, or when the snapshot no longer matches the sha256 pinned in backend.lock.json.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';
import { applyFixes, type FixReport, type OpenApiDocument } from './openapi-fix.ts';
import { GENERATED_FILE, LOCK_FILE, SNAPSHOT_FILE } from './paths.ts';

interface BackendLock {
  repo: string;
  commit: string;
  openapiSha256: string;
}

function fail(message: string): never {
  process.stderr.write(`api:gen: ${message}\n`);
  process.exit(1);
}

const check = process.argv.includes('--check');
const lock = JSON.parse(readFileSync(LOCK_FILE, 'utf8')) as BackendLock;
const snapshot = readFileSync(SNAPSHOT_FILE, 'utf8');
const sha256 = createHash('sha256').update(snapshot).digest('hex');
if (sha256 !== lock.openapiSha256) {
  fail('the snapshot does not match backend.lock.json; it was edited by hand. Run api:pull instead.');
}

const { document, report } = applyFixes(JSON.parse(snapshot) as OpenApiDocument);
// The one boundary cast: the corrected plain-JSON document is a valid OpenAPI 3.1 object for the generator.
const ast = await openapiTS(document as unknown as OpenAPI3);

const header = [
  '/**',
  ' * Generated by `npm run api:gen -w @nile/api`. Do not edit: change the snapshot (api:pull) or',
  ' * scripts/openapi-fix.ts and regenerate.',
  ` * Backend: ${lock.repo}@${lock.commit} (openapi sha256 ${lock.openapiSha256.slice(0, 16)}…).`,
  ' */',
  '',
].join('\n');
const output = `${header}${astToString(ast)}`;

const summary = (r: FixReport) =>
  `${r.nullableResponseProperties} nullable response fields, ${r.nullableRequestProperties} nullable request fields, ` +
  `${r.removedPhantomProperties} phantom properties removed`;

if (check) {
  let committed = '';
  try {
    committed = readFileSync(GENERATED_FILE, 'utf8');
  } catch {
    fail('src/generated/schema.d.ts is missing. Run api:gen and commit it.');
  }
  if (committed !== output) fail('src/generated/schema.d.ts is out of date. Run api:gen and commit it.');
  process.stdout.write(`api:check: generated types are up to date (${summary(report)})\n`);
} else {
  writeFileSync(GENERATED_FILE, output, 'utf8');
  process.stdout.write(`api:gen: wrote src/generated/schema.d.ts (${summary(report)})\n`);
}
